#include <stdio.h>
////Escape sequence : \n  \r \t \b \" \' %% \\n
int main() {
    printf("My name is \n Pranali Gulhane\n");
    printf("good  morining \r nice\n");
    printf("\t C \tcpp \tDS \n");
    printf("I am working on day2_3.c\b\b\b1\n");
    printf("\"How are you!\" \n");
    printf("\'Pranali\' \n");
    printf("I have scored 80%%\n");
    printf("\\n is a new line escape sequence\n");

    return 0;
}